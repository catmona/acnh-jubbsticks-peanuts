"""docs/index.html = head + body + engine + flow (all inline); docs/engine.js = the same engine as a classic script, which
the QoL page loads from /acnh-jubbsticks-peanuts/engine.js. The engine is fzstd (MIT) + app.js, wrapped so its names stay private."""
import os
H = os.path.dirname(os.path.abspath(__file__)); D = os.path.join(H, '..', 'docs')
r = lambda p: open(p, encoding='utf-8').read()
w = lambda p, s: open(p, 'w', encoding='utf-8', newline='\n').write(s)
engine = ('/* Jubbsticks Additions for Peanuts: the engine behind index.html (generated by tools/make_page.py). Exposes globalThis.JUB.\n'
          '   Includes fzstd 0.1.1, MIT, (c) 2020 Arjun Barrett */\n' + r(os.path.join(H, 'fzstd.umd.js'))
          + '\n;(function () {\n' + r(os.path.join(D, 'app.js'))
          + '\nglobalThis.JUB = { make, check, build, MEMFIX, memFixZip, writeZip };\n})();\n')
w(os.path.join(D, 'engine.js'), engine)
w(os.path.join(D, 'index.html'),
  r(os.path.join(D, 'head.html')) + r(os.path.join(D, 'body.html'))
  + '<script>\n' + engine + '</script>\n<script>window.FLOW_SELF = "jub";</script>\n<script>\n' + r(os.path.join(D, 'flow.js'))
  + '</script>\n</body>\n</html>\n')
